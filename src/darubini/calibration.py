"""Calibrate the quality gate on real fields.

Every field in the thick-film datasets was accepted by an expert annotator, so
the gate should almost never block one. To check the gate still catches bad
fields, each sample is also blurred (simulated defocus) and re-measured.
"""

from __future__ import annotations

import math
import random
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
from numpy.typing import NDArray
from scipy import ndimage

from darubini.data.profile import IMAGE_EXTS, SKIP_DIRS
from darubini.pipeline import load_image
from darubini.quality import QualityThresholds, assess, focus_gray, focus_score

#: Defocus blur levels (Gaussian sigma, in focus working-size pixels).
BLUR_SIGMAS: tuple[float, ...] = (2.0, 4.0)
PERCENTILES: tuple[int, ...] = (1, 5, 50, 95)


@dataclass
class DatasetSurvey:
    """Quality measurements for a sample of one dataset's fields."""

    dataset_id: str
    sharpness: list[float] = field(default_factory=list)
    brightness: list[float] = field(default_factory=list)
    stain: list[float] = field(default_factory=list)
    blocked: list[bool] = field(default_factory=list)
    blurred_sharpness: dict[float, list[float]] = field(default_factory=dict)

    @property
    def n(self) -> int:
        """Number of fields measured."""
        return len(self.sharpness)

    def reject_rate(self) -> float:
        """Share of real fields the gate blocks for any reason."""
        return sum(self.blocked) / self.n if self.n else 0.0

    def blur_catch_rate(self, sigma: float, min_sharpness: float) -> float:
        """Share of blurred copies the focus check would block."""
        values = self.blurred_sharpness.get(sigma, [])
        return sum(v < min_sharpness for v in values) / len(values) if values else 0.0


def field_images(root: Path) -> list[Path]:
    """Thick-film field images under ``root``, skipping crops and thin-smear folders."""
    out = []
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root).parts
        if path.suffix.lower() not in IMAGE_EXTS or not path.is_file():
            continue
        if any(p in SKIP_DIRS or "thin" in p.lower() or p.lower() == "crops" for p in rel):
            continue
        out.append(path)
    return out


def blurred_sharpness(image: NDArray[np.uint8], sigmas: Iterable[float]) -> dict[float, float]:
    """Focus score of ``image`` after Gaussian blur at each sigma (working-size pixels)."""
    gray = focus_gray(image)
    return {s: focus_score(ndimage.gaussian_filter(gray, s)) for s in sigmas}


def survey(
    dataset_id: str,
    root: Path,
    sample: int,
    thresholds: QualityThresholds | None = None,
    seed: int = 0,
) -> DatasetSurvey:
    """Measure a random sample of one dataset's fields, plus blurred copies."""
    t = thresholds or QualityThresholds()
    files = field_images(root)
    picked = random.Random(seed).sample(files, min(sample, len(files)))  # noqa: S311  # nosec B311
    result = DatasetSurvey(dataset_id, blurred_sharpness={s: [] for s in BLUR_SIGMAS})
    for path in picked:
        image = load_image(path)
        report = assess(image, t)
        result.sharpness.append(report.sharpness)
        result.brightness.append(report.brightness)
        result.stain.append(report.stain_fraction)
        result.blocked.append(not report.usable)
        for s, v in blurred_sharpness(image, BLUR_SIGMAS).items():
            result.blurred_sharpness[s].append(v)
    return result


def suggest_min_sharpness(surveys: Iterable[DatasetSurvey], max_reject: float = 0.01) -> float:
    """Largest round threshold that blocks at most ``max_reject`` of every dataset."""
    floors = [float(np.quantile(s.sharpness, max_reject, method="lower")) for s in surveys if s.n]
    if not floors:
        raise ValueError("no fields measured")
    lowest = min(floors)
    return math.floor(lowest * 2) / 2  # round down to 0.5


def render(surveys: list[DatasetSurvey], thresholds: QualityThresholds) -> str:
    """Markdown report of the survey under the given thresholds."""

    def pct(values: list[float], digits: int = 1) -> str:
        return " / ".join(f"{np.percentile(values, p):.{digits}f}" for p in PERCENTILES)

    head = " / ".join(f"p{p}" for p in PERCENTILES)
    blur_cols = " | ".join(f"Blur sigma={s:g} caught" for s in BLUR_SIGMAS)
    lines = [
        "# Quality gate calibration",
        "",
        "Generated by `darubini calibrate`. Each row is a random sample of expert-annotated",
        "thick-film fields, so every one should pass. Blurred copies simulate defocus; the",
        "focus check should block them.",
        "",
        f"Thresholds: min sharpness **{thresholds.min_sharpness:g}**, brightness "
        f"{thresholds.min_brightness:g} to {thresholds.max_brightness:g}.",
        "",
        "## Results",
        "",
        f"| Dataset | Fields | Blocked | {blur_cols} |",
        "| --- | ---: | ---: | " + " | ".join("---:" for _ in BLUR_SIGMAS) + " |",
    ]
    for s in surveys:
        catches = " | ".join(
            f"{s.blur_catch_rate(sigma, thresholds.min_sharpness):.0%}" for sigma in BLUR_SIGMAS
        )
        lines.append(f"| {s.dataset_id} | {s.n} | {s.reject_rate():.1%} | {catches} |")
    lines += [
        "",
        "## Measured values",
        "",
        f"| Dataset | Sharpness {head} | Brightness {head} | Stain fraction {head} |",
        "| --- | --- | --- | --- |",
    ]
    for s in surveys:
        lines.append(
            f"| {s.dataset_id} | {pct(s.sharpness)} | {pct(s.brightness)} | {pct(s.stain, 3)} |"
        )
    return "\n".join(lines) + "\n"
