    fun tool(name: String): String = tools[name] ?: name

    fun number(n: Int): String = NumberFormat.getIntegerInstance(Locale.US).format(n)

    /** The word for a slide's counting status ("continue", "complete", "negative"). */
    fun statusWord(status: String): String = when (status) {
        "complete" -> complete
        "negative" -> negative
        else -> inProgress
    }
}

