"""Development check of two-stage detection: does SAM 3.1 box confirmation help?

Every parasite candidate (after dropping those inside a WBC) gets the verifier's
probability and SAM 3.1's box-prompt confidence. Rules are then compared on the same
candidates: candidates alone, verifier alone, SAM confirmation alone, and both.

Development data only (NIH val, UDOM check); the test sets were scored once already.

Usage:
    python scripts/two_stage.py run      # SAM calls, cached; about US$3
    python scripts/two_stage.py report   # writes docs/calibration/two_stage.md
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

import numpy as np

from darubini.config import get_settings
from darubini.data.fields import LabelledField, nlm_thick_fields, udom_fields
from darubini.evaluation import match_centres
from darubini.meta.client import MetaModelClient
from darubini.pipeline import load_image
from darubini.segmentation.candidates import CandidateDetector
from darubini.segmentation.confirm import BoxConfirmer
from darubini.segmentation.sam import TUNED_MIN_SCORES, SamSegmenter, drop_parasites_in_wbc
from darubini.types import BoundingBox, Detection, ObjectClass
from darubini.verifier import ParasiteVerifier, candidate_features

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "datasets" / "raw"
OUT = ROOT / "datasets" / "processed" / "two_stage"
REPORT = ROOT / "docs" / "calibration" / "two_stage.md"
SEED = 0
SETS = {"nih_val": 20, "udom_check": 150}


def fields(name: str) -> list[LabelledField]:
    if name == "nih_val":
        out = nlm_thick_fields(RAW / "nih-thick-pf-150", "val")
    else:
        out = udom_fields(RAW / "udom-tz-thick", "check")
    random.Random(SEED).shuffle(out)
    return out[: SETS[name]]


def run() -> None:
    s = get_settings()
    client = MetaModelClient.from_settings(s)
    model = s.meta_segmentation_model
    wbc = SamSegmenter(
        client, model, concepts={"cell": ObjectClass.WBC}, class_min_score=TUNED_MIN_SCORES
    )
    detector, verifier = CandidateDetector(), ParasiteVerifier.load(s.verifier_path)
    confirmer = BoxConfirmer(client, model)
    OUT.mkdir(parents=True, exist_ok=True)
    for name in SETS:
        path = OUT / f"{name}.jsonl"
        done = (
            {json.loads(x)["key"] for x in path.read_text().splitlines()}
            if path.exists()
            else set()
        )
        with path.open("a", encoding="utf-8") as fh:
            for n, f in enumerate(fields(name), 1):
                if str(f.image) in done:
                    continue
                image = load_image(f.image)
                wbcs = [d for d in wbc.segment(image) if d.cls is ObjectClass.WBC]
                found = [d for d in detector.segment(image) if d.cls is ObjectClass.PARASITE]
                cands = [
                    d
                    for d in drop_parasites_in_wbc([*wbcs, *found])
                    if d.cls is ObjectClass.PARASITE
                ]
                proba = verifier.predict_proba(candidate_features(image, cands))
                conf = confirmer.confidences(image, [d.box for d in cands])
                row = {
                    "key": str(f.image),
                    "cands": [
                        [d.box.x_min, d.box.y_min, d.box.x_max, d.box.y_max, round(float(p), 4), c]
                        for d, p, c in zip(cands, proba, conf, strict=True)
                    ],
                }
                fh.write(json.dumps(row) + "\n")
                fh.flush()
                print(
                    f"{name} {n}: {len(cands)} candidates, {client.billed_requests} billed",
                    flush=True,
                )


def f1(rows: list[dict], truth: dict[str, list[Detection]], keep) -> tuple[float, float, float]:  # type: ignore[no-untyped-def]
    tp = fp = fn = 0
    for r in rows:
        pred = [
            Detection(ObjectClass.PARASITE, BoundingBox(*c[:4]), 1.0)
            for c in r["cands"]
            if keep(c[4], c[5])
        ]
        t = [d for d in truth[r["key"]] if d.cls is ObjectClass.PARASITE]
        m = match_centres(pred, t, ObjectClass.PARASITE)
        tp, fp, fn = tp + m.true_positives, fp + m.false_positives, fn + m.false_negatives
    p = tp / (tp + fp) if tp + fp else 0.0
    r_ = tp / (tp + fn) if tp + fn else 0.0
    return p, r_, (2 * p * r_ / (p + r_) if p + r_ else 0.0)


def report() -> None:
    v_t = ParasiteVerifier.load(get_settings().verifier_path).threshold
    grid = [round(x, 2) for x in np.arange(0.50, 0.91, 0.02)]
    lines = [
        "# Two-stage detection: SAM 3.1 box confirmation (development data)",
        "",
        "Generated by `scripts/two_stage.py report`. Every parasite candidate outside a WBC gets "
        "the verifier's probability *p* and SAM 3.1's box-prompt confidence *c* (16 boxes per "
        "request, on the 1,024 px tile holding the candidate). Development data only: "
        f"{SETS['nih_val']} NIH val fields and {SETS['udom_check']} UDOM `check` tiles (seed 0).",
        "",
    ]
    best_c: dict[str, float] = {}
    for name in SETS:
        rows = [json.loads(x) for x in (OUT / f"{name}.jsonl").read_text().splitlines()]
        truth = {str(f.image): list(f.truth) for f in fields(name)}
        sam_best = max(grid, key=lambda t: f1(rows, truth, lambda p, c, t=t: c >= t)[2])
        both_best = max(
            grid, key=lambda t: f1(rows, truth, lambda p, c, t=t: p >= v_t and c >= t)[2]
        )
        best_c[name] = both_best
        rules = [
            ("Candidates alone", lambda p, c: True),
            (f"Verifier, p ≥ {v_t}", lambda p, c: p >= v_t),
            (
                f"SAM confirmation alone, c ≥ {sam_best} (best on this set)",
                lambda p, c, t=sam_best: c >= t,
            ),
            (
                f"Two-stage: p ≥ {v_t} and c ≥ {both_best} (best on this set)",
                lambda p, c, t=both_best: p >= v_t and c >= t,
            ),
        ]
        n_c = sum(len(r["cands"]) for r in rows)
        lines += [f"## {name} ({len(rows)} fields, {n_c} candidates)", ""]
        lines += ["| Rule | Precision | Recall | F1 |", "| --- | ---: | ---: | ---: |"]
        for label, keep in rules:
            p, r_, f = f1(rows, truth, keep)
            lines.append(f"| {label} | {p:.2f} | {r_:.2f} | {f:.2f} |")
        c_all = np.array([c[5] for r in rows for c in r["cands"]])
        lines += [
            "",
            f"SAM segmented {np.mean(c_all > 0):.0%} of candidates; median *c* {np.median(c_all):.2f}.",
            "",
        ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(REPORT.read_text(encoding="utf-8"))
    print(json.dumps(best_c))


if __name__ == "__main__":
    {"run": run, "report": report}[sys.argv[1]]()
